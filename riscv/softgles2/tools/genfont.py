#!/usr/bin/env python3
"""Generate the softgles2 stats-overlay bitmap font header.

The overlay draws straight into the framebuffer on a machine with no OS, no
font files and no asset pipeline, so the glyphs have to be compiled in. This
rasterises a monospace TTF once, on the host, into a packed 1-bit-per-pixel
array and writes it as C.

Regenerate with:
    python3 riscv/softgles2/tools/genfont.py

Deliberately committed as generated output: the build must not depend on
Pillow, on a system font, or on a network fetch.
"""
import sys

from PIL import Image, ImageDraw, ImageFont

FONT = "/usr/share/fonts/truetype/ubuntu/UbuntuMono-R.ttf"
SIZE = 13
FIRST, LAST = 32, 126          # printable ASCII
CELL_W, CELL_H = 7, 14         # advance / line height
INK_TOP = 2                    # first row with ink at this size
THRESHOLD = 70                 # antialiased coverage -> on/off
OUT = "riscv/softgles2/src/sg_overlay_font.h"


def render_glyph(font, ch):
    """Return CELL_H bytes, MSB = leftmost pixel."""
    img = Image.new("L", (16, 24), 0)
    ImageDraw.Draw(img).text((0, -INK_TOP), ch, 255, font=font)
    rows = []
    for y in range(CELL_H):
        bits = 0
        for x in range(8):
            if img.getpixel((x, y)) > THRESHOLD:
                bits |= 0x80 >> x
        rows.append(bits)
    return rows


def main():
    font = ImageFont.truetype(FONT, SIZE)
    glyphs = [render_glyph(font, chr(c)) for c in range(FIRST, LAST + 1)]

    with open(OUT, "w") as f:
        f.write(
            "/* GENERATED by riscv/softgles2/tools/genfont.py -- do not edit.\n"
            " *\n"
            " * %dx%d monospace bitmap font, printable ASCII %d..%d.\n"
            " * One byte per glyph row, MSB = leftmost pixel. Rendered from\n"
            " * %s at %dpx.\n"
            " */\n"
            "#ifndef SOFTGLES2_SG_OVERLAY_FONT_H\n"
            "#define SOFTGLES2_SG_OVERLAY_FONT_H\n\n"
            "#define SGL_FONT_W     %d\n"
            "#define SGL_FONT_H     %d\n"
            "#define SGL_FONT_FIRST %d\n"
            "#define SGL_FONT_LAST  %d\n\n"
            "static const unsigned char sgl_font_bits[%d][%d] = {\n"
            % (CELL_W, CELL_H, FIRST, LAST, FONT.split("/")[-1], SIZE,
               CELL_W, CELL_H, FIRST, LAST, len(glyphs), CELL_H)
        )
        for i, rows in enumerate(glyphs):
            ch = chr(FIRST + i)
            label = "space" if ch == " " else ch
            if ch in ("\\", '"'):
                label = "\\" + ch
            f.write("    { %s },  /* '%s' */\n"
                    % (", ".join("0x%02x" % r for r in rows), label))
        f.write("};\n\n#endif /* SOFTGLES2_SG_OVERLAY_FONT_H */\n")

    print("wrote %s (%d glyphs, %d bytes of glyph data)"
          % (OUT, len(glyphs), len(glyphs) * CELL_H))


if __name__ == "__main__":
    sys.exit(main())
